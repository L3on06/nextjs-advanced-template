export const firebaseAdminStep: StepDef = {
  id: "firebase-admin",
  title: "Firebase Admin",
  schema: z
    .object({
      mode: z.enum(["emulator", "service-account"]),
      projectId: z.string().min(1).optional(),
      clientEmail: z.string().email().optional(),
      privateKey: z.string().min(1).optional(),
    })
    .refine(
      (value) =>
        value.mode === "emulator" ||
        (Boolean(value.projectId) && Boolean(value.clientEmail) && Boolean(value.privateKey)),
      { message: "service-account mode requires projectId, clientEmail, and privateKey" },
    ),
  ui: {
    title: "Admin credentials",
    description: "Emulators need nothing. Deploys need a service account, which is written straight to .env.local and never stored in setup state.",
    fields: [
      { name: "mode", label: "Credential mode", type: "select", options: ["emulator", "service-account"] },
      { name: "projectId", label: "Admin project ID", type: "text" },
      { name: "clientEmail", label: "Client email", type: "text" },
      { name: "privateKey", label: "Private key", type: "secret", secret: true },
    ],
  },
  docs: "Configures server privilege. Emulator mode needs no secrets. Service account mode merges the three credential vars into .env.local without touching existing keys, and the private key is flagged secret so it never lands in setup state or logs.",
  detect: (targetDir, values) => {
    if (values["mode"] === "emulator") {
      const firebase = readJsonFile(targetDir, "firebase.json") as { emulators?: unknown } | null;
      return firebase?.emulators
        ? { status: "current", detail: "emulator mode with emulator config present" }
        : { status: "missing", detail: "emulator config not yet generated" };
    }
    const local = parseEnvFile(targetDir);
    return local["FIREBASE_ADMIN_PROJECT_ID"]
      ? { status: "current", detail: "admin project id present in .env.local" }
      : { status: "missing", detail: "admin credentials not yet provided" };
  },
  generate: (ctx) => {
    if (ctx.values["mode"] === "emulator") return [];
    return [mergeLocalEnv(ctx.targetDir, ctx.values)];
  },
};

function parseEnvFile(targetDir: string): Record<string, string> {
  const absolute = join(targetDir, ".env.local");
  if (!existsSync(absolute)) return {};
  const out: Record<string, string> = {};
  for (const line of readFileSync(absolute, "utf8").split("\n")) {
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (match) out[match[1]] = match[2];
  }
  return out;
}

/** Merge credential vars into .env.local without overwriting existing keys. */
function mergeLocalEnv(targetDir: string, values: Record<string, unknown>): Extract<ReturnType<StepDef["generate"]>[number], { path: string }> {
  const current = parseEnvFile(targetDir);
  const wanted: Record<string, string> = {
    FIREBASE_ADMIN_PROJECT_ID: values["projectId"] as string,
    FIREBASE_ADMIN_CLIENT_EMAIL: values["clientEmail"] as string,
    FIREBASE_ADMIN_PRIVATE_KEY: values["privateKey"] as string,
  };
  const next = { ...wanted, ...current };
  const content = `${Object.entries(next)
    .map(([key, value]) => `${key}=${value}`)
    .join("\n")}\n`;
  return { path: ".env.local", content, owned: "generated" };
}

