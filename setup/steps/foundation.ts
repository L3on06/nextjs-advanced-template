const INDEXES_STARTER = `{
  "indexes": [],
  "fieldOverrides": []
}
`;

export const firestoreStep: StepDef = {
  id: "firestore",
  title: "Firestore",
  schema: z.object({
    rulesFile: z.string().min(1).default("firestore.rules"),
    indexesFile: z.string().min(1).default("firestore.indexes.json"),
  }),
  ui: {
    title: "Firestore",
    description: "Point firebase.json at the rules and indexes files. Rules compile at the final stamp.",
    fields: [
      { name: "rulesFile", label: "Rules file", type: "text" },
      { name: "indexesFile", label: "Indexes file", type: "text" },
    ],
  },
  docs: "Wires the Firestore rules and indexes paths. The rules file itself compiles from the authorization model at the generate step, so this step only guarantees the pointer plus a valid starter indexes file (existing valid indexes are preserved).",
  detect: (targetDir, values) => {
    const firebase = readJsonFile(targetDir, "firebase.json") as { firestore?: unknown } | null;
    const indexes = readJsonFile(targetDir, values["indexesFile"] as string) as {
      indexes?: unknown;
    } | null;
    const ok =
      JSON.stringify(firebase?.firestore) ===
        JSON.stringify({ rules: values["rulesFile"], indexes: values["indexesFile"] }) &&
      Array.isArray(indexes?.indexes);
    return ok
      ? { status: "current", detail: "firestore wiring valid" }
      : { status: "missing", detail: "firestore wiring missing or stale" };
  },
  generate: (ctx) => {
    const files = [firebaseJsonMerge(ctx.targetDir, "firestore", {
      rules: ctx.values["rulesFile"],
      indexes: ctx.values["indexesFile"],
    })];
    const existing = readJsonFile(ctx.targetDir, ctx.values["indexesFile"] as string) as {
      indexes?: unknown;
    } | null;
    if (!Array.isArray(existing?.indexes)) {
      files.push({ path: ctx.values["indexesFile"] as string, content: INDEXES_STARTER, owned: "generated" });
    }
    return files;
  },
};

