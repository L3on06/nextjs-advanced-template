function initials(name: string): string {
  return name
    .split(/\s+/)
    .map((word) => word[0] ?? "")
    .join("")
    .slice(0, 2)
    .toUpperCase();
}

function logoSvg(values: Record<string, unknown>): string {
  const name = values["brandName"] as string;
  const color = values["brandColor"] as string;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128">
  <rect width="128" height="128" rx="28" fill="${color}" />
  <text x="64" y="82" font-family="system-ui, sans-serif" font-size="56" font-weight="700" fill="#ffffff" text-anchor="middle">${initials(name)}</text>
</svg>
`;
}

function ogSvg(values: Record<string, unknown>): string {
  const name = values["brandName"] as string;
  const color = values["brandColor"] as string;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="${color}" />
  <text x="600" y="345" font-family="system-ui, sans-serif" font-size="96" font-weight="700" fill="#ffffff" text-anchor="middle">${name}</text>
</svg>
`;
}

