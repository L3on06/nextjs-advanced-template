function typographyBody(values: Record<string, unknown>): string {
  return `:root {
  --font-sans: ${values["fontFamily"]}, system-ui, sans-serif;
  --font-mono: ${values["monoFamily"]}, monospace;
  --font-size-base: ${values["baseSize"]}px;
}`;
}

function sectionBlock(marker: string, body: string): string {
  return `/* setup:${marker} -- managed, do not hand edit */\n${body}\n/* setup:end-${marker} */`;
}

/** Replace (or append) a marked section inside a CSS file. Other sections survive. */
export function applySection(targetDir: string, relPath: string, marker: string, body: string): string {
  const absolute = join(targetDir, relPath);
  const current = existsSync(absolute) ? readFileSync(absolute, "utf8") : "";
  const pattern = new RegExp(`/\\* setup:${marker}[\\s\\S]*?/\\* setup:end-${marker} \\*/`, "m");
  const block = sectionBlock(marker, body);
  if (pattern.test(current)) return current.replace(pattern, () => block);
  const separator = current === "" || current.endsWith("\n") ? "" : "\n";
  return `${current}${separator}\n${block}\n`;
}

function sectionMatches(targetDir: string, relPath: string, marker: string, body: string): boolean {
  const absolute = join(targetDir, relPath);
  if (!existsSync(absolute)) return false;
  return readFileSync(absolute, "utf8").includes(sectionBlock(marker, body));
}

