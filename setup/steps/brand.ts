function designBody(values: Record<string, unknown>): string {
  const radius = values["radius"] as string;
  return `:root {
  --primary: ${values["primaryColor"]};
  --radius: ${radius}rem;
}
.dark {
  --primary: ${values["primaryColor"]};
}`;
}

