const HexColor = z.string().regex(/^#[0-9a-fA-F]{6}$/, "hex color like #1d4ed8");

export const metadataStep: StepDef = {
  id: "app-metadata",
  title: "Application metadata",
  schema: z.object({
    appName: z.string().min(1).max(60),
    tagline: z.string().min(1).max(140),
    defaultLocale: z.enum(["en", "al"]).default("en"),
    baseUrl: z.string().url().optional(),
  }),
  ui: {
    title: "Application metadata",
    description: "Name, tagline, default language, and canonical base URL.",
    fields: [
      { name: "appName", label: "Application name", type: "text" },
      { name: "tagline", label: "Tagline", type: "text" },
      { name: "defaultLocale", label: "Default locale", type: "select", options: ["en", "al"] },
      { name: "baseUrl", label: "Canonical base URL", type: "text" },
    ],
  },
  docs: "Records the application's public identity. Downstream steps (languages, SEO, branding) read these values from setup state instead of asking again. Never stores secrets.",
  detect: (targetDir, values) => {
    const ok = fileMatches(
      targetDir,
      "shared/app-meta/generated.ts",
      metaContent(values["appName"] as string, values["tagline"] as string, values["defaultLocale"] as string),
    );
    return ok
      ? { status: "current", detail: "metadata matches" }
      : { status: "missing", detail: "metadata missing or stale" };
  },
  generate: (ctx) => [
    {
      path: "shared/app-meta/generated.ts",
      content: metaContent(
        ctx.values["appName"] as string,
        ctx.values["tagline"] as string,
        ctx.values["defaultLocale"] as string,
      ),
      owned: "generated",
    },
  ],
};

function metaContent(appName: string, tagline: string, defaultLocale: string): string {
  return `// GENERATED by setup (app-metadata). Do not hand edit.
export const APP_META = {
  appName: ${JSON.stringify(appName)},
  tagline: ${JSON.stringify(tagline)},
  defaultLocale: ${JSON.stringify(defaultLocale)},
} as const;
`;
}

