export const languagesStep: StepDef = {
  id: "languages",
  title: "Languages",
  schema: z.object({
    locales: z.array(z.enum(["en", "al"])).min(1).default(["en", "al"]),
    primaryLocale: z.enum(["en", "al"]).default("en"),
  }),
  ui: {
    title: "Languages",
    description: "Enabled locales plus the primary one. Starter message files merge, never overwrite.",
    fields: [
      { name: "locales", label: "Enabled locales", type: "multiselect", options: ["en", "al"] },
      { name: "primaryLocale", label: "Primary locale", type: "select", options: ["en", "al"] },
    ],
  },
  docs: "Writes starter message files per enabled locale. Existing keys always win on merge, so reruns and custom copy survive. Keys stay flat and mirrored per the translations skill.",
  detect: (targetDir, values) => {
    const locales = values["locales"] as string[];
    const ok = locales.every((locale) => {
      const current = readJsonFile(targetDir, `messages/${locale}.json`) as Record<string, string> | null;
      if (!current) return false;
      return Object.keys(STARTER_KEYS[locale] ?? {}).every((key) => key in current);
    });
    return ok
      ? { status: "current", detail: "starter messages present" }
      : { status: "missing", detail: "starter messages missing or stale" };
  },
  generate: (ctx) => {
    const locales = ctx.values["locales"] as string[];
    const appName = (ctx.prior["app-metadata"]?.["appName"] as string | undefined) ?? "App";
    return locales.map((locale) =>
      messagesMerge(ctx.targetDir, locale, {
        "app.name": appName,
        ...(STARTER_KEYS[locale] ?? {}),
      }),
    );
  },
};
